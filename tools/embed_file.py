"""
Converts binary files to a C source file, to embed them in the firmware.

Defines ``pb_mp3_song_data``, an array of pointers to the file contents,
``pb_mp3_song_size`` with their sizes in bytes, and ``pb_mp3_song_count``.
"""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="C file to write")
    parser.add_argument("input", type=Path, nargs="+", help="files to embed")
    args = parser.parse_args()

    lines = [
        "// Generated by tools/embed_file.py. Do not edit.",
        "",
        "#include <stdint.h>",
        "",
    ]

    sizes = []

    for index, path in enumerate(args.input):
        data = path.read_bytes()
        sizes.append(len(data))
        lines.append(f"// {path.name}")
        lines.append(f"static const uint8_t song_{index}[] __attribute__((aligned(4))) = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + " ".join(f"0x{b:02x}," for b in data[i : i + 16]))
        lines.append("};")
        lines.append("")

    pointers = ", ".join(f"song_{i}" for i in range(len(args.input)))
    lengths = ", ".join(str(size) for size in sizes)

    lines += [
        f"const uint8_t *const pb_mp3_song_data[] = {{{pointers}}};",
        "",
        f"const uint32_t pb_mp3_song_size[] = {{{lengths}}};",
        "",
        f"const uint32_t pb_mp3_song_count = {len(args.input)};",
        "",
    ]

    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()

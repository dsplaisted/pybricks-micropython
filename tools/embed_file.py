"""
Converts a binary file to a C source file, to embed it in the firmware.

Defines ``const uint8_t <name>[]`` with the file contents and
``const uint32_t <name>_size`` with its size in bytes.
"""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", help="C symbol name")
    parser.add_argument("input", type=Path, help="file to embed")
    parser.add_argument("output", type=Path, help="C file to write")
    args = parser.parse_args()

    data = args.input.read_bytes()

    lines = [
        "// Generated by tools/embed_file.py. Do not edit.",
        "",
        "#include <stdint.h>",
        "",
        f"const uint8_t {args.name}[] __attribute__((aligned(4))) = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[i : i + 16]))
    lines += [
        "};",
        "",
        f"const uint32_t {args.name}_size = {len(data)};",
        "",
    ]

    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
